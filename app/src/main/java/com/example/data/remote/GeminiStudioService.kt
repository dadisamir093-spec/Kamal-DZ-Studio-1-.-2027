private const val BACKEND_URL = "https://kamal-dz-studio-1---2027.faycallakal17.workers.dev"

object GeminiStudioService {

    private const val TAG = "GeminiStudioService"
    private var isAppCheckInitialized = false

    /**
     * Initializes Firebase App Check in a free-tier compliant way.
     * Uses PlayIntegrity in Release mode and DebugAppCheckProviderFactory in Debug mode.
     */
    fun initializeAppCheck(context: Context) {
        if (!isAppCheckInitialized) {
            try {
                val appCheckInstance = Firebase.appCheck
                if (BuildConfig.DEBUG) {
                    val factory = DebugAppCheckProviderFactory.getInstance()
                    appCheckInstance.installAppCheckProviderFactory(factory)
                    // Trigger provider creation immediately to instantiate and persist the debug secret
                    try {
                        val firebaseApp = com.google.firebase.FirebaseApp.getInstance()
                        factory.create(firebaseApp)
                    } catch (ignored: Exception) {}
                    Log.d(TAG, "Firebase App Check Debug Provider installed.")
                } else {
                    appCheckInstance.installAppCheckProviderFactory(
                        PlayIntegrityAppCheckProviderFactory.getInstance()
                    )
                    Log.d(TAG, "Firebase App Check initialized with Play Integrity Provider.")
                }
                isAppCheckInitialized = true
            } catch (e: Exception) {
                Log.e(TAG, "Error initializing App Check: ${e.message}", e)
            }
        }
    }

    /**
     * Resolves the actual Debug Secret generated by Firebase App Check Debug Provider.
     * Accessible strictly within DEBUG builds.
     */
    fun getDebugSecretToken(context: Context): String? {
        if (!BuildConfig.DEBUG) return null
        return try {
            val app = com.google.firebase.FirebaseApp.getInstance()
            val storageHelper = com.google.firebase.appcheck.debug.internal.StorageHelper(context, app.persistenceKey)
            val existing = storageHelper.retrieveDebugSecret()
            if (existing != null) {
                existing
            } else {
                val newSecret = java.util.UUID.randomUUID().toString()
                storageHelper.saveDebugSecret(newSecret)
                newSecret
            }
        } catch (e: Exception) {
            Log.e(TAG, "Error obtaining debug secret token: ${e.message}")
            null
        }
    }

    /**
     * Instantiates GenerativeModel bound explicitly to GenerativeBackend.googleAI() on the free Firebase Spark plan.
     */
    private fun getModel(systemInstructionText: String? = null): GenerativeModel {
        val sysContent = if (systemInstructionText != null) {
            content { text(systemInstructionText) }
        } else null

        return Firebase.ai.generativeModel(
            modelName = "gemini-2.5-flash",
            systemInstruction = sysContent
        )
    }

    /**
     * Free Spark Plan feature: Optimizes a raw user prompt into an expanded, high-quality Arabic cinematic prompt.
     */
    suspend fun optimizeCinematicPrompt(rawPrompt: String, cameraStyle: String, mode: String): Result<String> {
        return withContext(Dispatchers.IO) {
            try {
                val sysInstruction = """
                    أنت خبير إخراج سينمائي ومساعد ذكي لتوليد الفيديوهات والصور السينمائية.
                    مهمتك إعادة صياغة برومبت المستخدم وتوسيعه بأسلوب سينمائي دقيق باللغة العربية الفصحى.
                    أضف تفاصيل الإضاءة الحجمية (Volumetric Lighting)، زاوية الكاميرا ($cameraStyle)، العدسة (Anamorphic/Portrait)، الألوان (Teal & Orange)، وجودة الإطارات.
                    اجعل الإجابة مباشرة عبارة عن النص السينمائي المحسّن فقط دون مقدمات أو شرح.
                """.trimIndent()

                val generativeModel = getModel(systemInstructionText = sysInstruction)
                val response = generativeModel.generateContent("نمط العمل: $mode\nنص المستخدم: $rawPrompt")
                val text = response.text?.trim()
                if (!text.isNullOrEmpty()) {
                    Result.success(text)
                } else {
                    Result.failure(Exception("لم يتم استلام نص من نموذج Gemini"))
                }
            } catch (e: Exception) {
                Log.e(TAG, "Error optimizing prompt with Gemini: ${e.message}", e)
                Result.failure(e)
            }
        }
    }

    /**
     * Free Spark Plan feature: Generates cinematic script scene breakdowns for character and video generation.
     */
    suspend fun generateSceneBreakdown(storyIdea: String): Result<String> {
        return withContext(Dispatchers.IO) {
            try {
                val sysInstruction = """
                    أنت كاتب سيناريو ومخرج سينمائي محترف.
                    قم بتحليل الفكرة التالية وتقسيمها إلى مشاهد سينمائية قصيرة جاهزة للتوليد.
                    لكل مشهد حدد: رقم المشهد، الوصف البصري، حركة الكاميرا، ونوع الإضاءة.
                """.trimIndent()

                val generativeModel = getModel(systemInstructionText = sysInstruction)
                val response = generativeModel.generateContent(storyIdea)
                val text = response.text?.trim()
                if (!text.isNullOrEmpty()) {
                    Result.success(text)
                } else {
                    Result.failure(Exception("استجابة فارغة من النموذج"))
                }
            } catch (e: Exception) {
                Log.e(TAG, "Error generating scene breakdown: ${e.message}", e)
                Result.failure(e)
            }
        }
    }

    data class QuotaInfo(
        val date: String,
        val usedNeurons: Int,
        val dailyLimit: Int,
        val remainingNeurons: Int
    )

    suspend fun fetchDailyQuotaInfo(context: Context): Result<QuotaInfo> {
        return withContext(Dispatchers.IO) {
            try {
                val url = java.net.URL("$BACKEND_URL/ai/quota-info")
                val connection = url.openConnection() as java.net.HttpURLConnection
                connection.requestMethod = "GET"
                connection.connectTimeout = 5000
                connection.readTimeout = 5000

                if (connection.responseCode == 200) {
                    val json = connection.inputStream.bufferedReader().use { it.readText() }
                    val obj = org.json.JSONObject(json)
                    val info = QuotaInfo(
                        date = obj.optString("date", ""),
                        usedNeurons = obj.optInt("usedNeurons", 0),
                        dailyLimit = obj.optInt("dailyLimit", 10000),
                        remainingNeurons = obj.optInt("remainingNeurons", 10000)
                    )
                    Result.success(info)
                } else {
                    Result.failure(Exception("HTTP error ${connection.responseCode}"))
                }
            } catch (e: Exception) {
                Result.failure(e)
            }
        }
    }

    suspend fun generateImageWithCloudflareWorker(
        context: Context,
        prompt: String,
        width: Int = 1024,
        height: Int = 576,
        steps: Int = 4
    ): Result<java.io.File> {
        return withContext(Dispatchers.IO) {
            try {
                // Obtain App Check token string via Firebase App Check SDK
                var appCheckToken: String? = null
                try {
                    val tokenTask = com.google.firebase.appcheck.FirebaseAppCheck.getInstance().getAppCheckToken(false)
                    val tokenResult = com.google.android.gms.tasks.Tasks.await(tokenTask)
                    appCheckToken = tokenResult.token
                } catch (e: Exception) {
                    Log.w(TAG, "App Check token task failed: ${e.message}")
                }

                val url = java.net.URL("$BACKEND_URL/ai/generate-image")
                val connection = url.openConnection() as java.net.HttpURLConnection
                connection.requestMethod = "POST"
                connection.setRequestProperty("Content-Type", "application/json")
                if (!appCheckToken.isNullOrEmpty()) {
                    connection.setRequestProperty("X-Firebase-AppCheck", appCheckToken)
                    connection.setRequestProperty("Authorization", "Bearer $appCheckToken")
                }
                val requestId = java.util.UUID.randomUUID().toString()
                connection.setRequestProperty("X-Request-ID", requestId)
                connection.connectTimeout = 30000
                connection.readTimeout = 60000
                connection.doOutput = true

                val requestBody = org.json.JSONObject().apply {
                    put("prompt", prompt)
                    put("width", width)
                    put("height", height)
                    put("steps", steps)
                }.toString()

                connection.outputStream.use { os ->
                    os.write(requestBody.toByteArray(Charsets.UTF_8))
                }

                val responseCode = connection.responseCode
                if (responseCode == 200) {
                    val bytes = connection.inputStream.use { it.readBytes() }
                    
                    val outputDir = java.io.File(context.filesDir, "generated_images")
                    if (!outputDir.exists()) outputDir.mkdirs()
                    val fileName = "cinematic_${System.currentTimeMillis()}.jpg"
                    val outputFile = java.io.File(outputDir, fileName)
                    outputFile.writeBytes(bytes)

                    Result.success(outputFile)
                } else {
                    val errorStream = connection.errorStream
                    val errorText = errorStream?.bufferedReader()?.use { it.readText() } ?: "HTTP $responseCode"
                    val errorMsg = try {
                        org.json.JSONObject(errorText).optString("error", errorText)
                    } catch (e: Exception) { errorText }
                    Result.failure(Exception(errorMsg))
                }
            } catch (e: Exception) {
                Log.e(TAG, "Error calling Cloudflare Worker generate-image: ${e.message}", e)
                Result.failure(e)
            }
        }
    }
}
