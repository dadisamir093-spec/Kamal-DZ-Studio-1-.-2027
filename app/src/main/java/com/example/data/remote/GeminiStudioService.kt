    data class QuotaInfo(
        val date: String,
        val usedNeurons: Int,
        val dailyLimit: Int,
        val remainingNeurons: Int
    )

    suspend fun fetchDailyQuotaInfo(context: Context): Result<QuotaInfo> {
        return withContext(Dispatchers.IO) {
            try {
                val url = java.net.URL("$BACKEND_URL/ai/quota-info")
                val connection = url.openConnection() as java.net.HttpURLConnection
                connection.requestMethod = "GET"
                connection.connectTimeout = 5000
                connection.readTimeout = 5000

                if (connection.responseCode == 200) {
                    val json = connection.inputStream.bufferedReader().use { it.readText() }
                    val obj = org.json.JSONObject(json)
                    val info = QuotaInfo(
                        date = obj.optString("date", ""),
                        usedNeurons = obj.optInt("usedNeurons", 0),
                        dailyLimit = obj.optInt("dailyLimit", 10000),
                        remainingNeurons = obj.optInt("remainingNeurons", 10000)
                    )
                    Result.success(info)
                } else {
                    Result.failure(Exception("HTTP error ${connection.responseCode}"))
                }
            } catch (e: Exception) {
                Result.failure(e)
            }
        }
    }

    suspend fun generateImageWithCloudflareWorker(
        context: Context,
        prompt: String,
        width: Int = 1024,
        height: Int = 576,
        steps: Int = 8
    ): Result<WorkerImageResult> {
        return withContext(Dispatchers.IO) {
            try {
                // Obtain App Check token string via Firebase App Check SDK
                var appCheckToken: String? = null
                var appCheckError: String? = null
                try {
                    val tokenTask = com.google.firebase.appcheck.FirebaseAppCheck.getInstance().getAppCheckToken(false)
                    val tokenResult = com.google.android.gms.tasks.Tasks.await(
                        tokenTask, 20, java.util.concurrent.TimeUnit.SECONDS
                    )
                    appCheckToken = tokenResult.token
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    Log.w(TAG, "App Check token task failed: ${e.message}")
                    appCheckError = e.message ?: e.javaClass.simpleName
                }

                if (appCheckToken.isNullOrEmpty()) {
                    return@withContext Result.failure(
                        Exception("تعذّر الحصول على توكن Firebase App Check من الجهاز: ${appCheckError ?: "التوكن فارغ"}. لم يُرسَل أي طلب إلى الخادم.")
                    )
                }

                val url = java.net.URL("$BACKEND_URL/ai/generate-image")
                val connection = url.openConnection() as java.net.HttpURLConnection
                connection.requestMethod = "POST"
                connection.setRequestProperty("Content-Type", "application/json")
                connection.setRequestProperty("X-Firebase-AppCheck", appCheckToken)
                connection.setRequestProperty("Authorization", "Bearer $appCheckToken")
                val requestId = java.util.UUID.randomUUID().toString()
                connection.setRequestProperty("X-Request-ID", requestId)
                connection.connectTimeout = 30000
                connection.readTimeout = 60000
                connection.doOutput = true

                val requestBody = org.json.JSONObject().apply {
                    put("prompt", prompt)
                    put("width", width)
                    put("height", height)
                    put("steps", steps)
                }.toString()

                connection.outputStream.use { os ->
                    os.write(requestBody.toByteArray(Charsets.UTF_8))
                }

                val responseCode = connection.responseCode
                if (responseCode == 200) {
                    val bytes = connection.inputStream.use { it.readBytes() }
                    val bounds = android.graphics.BitmapFactory.Options().apply { inJustDecodeBounds = true }
                    android.graphics.BitmapFactory.decodeByteArray(bytes, 0, bytes.size, bounds)
                    if (bytes.isEmpty() || bounds.outWidth <= 0 || bounds.outHeight <= 0) {
                        return@withContext Result.failure(
                            Exception("استجاب الخادم بنجاح لكن البيانات المستلمة ليست صورة صالحة (${bytes.size} بايت)")
                        )
                    }
                    
                    val outputDir = java.io.File(context.filesDir, "generated_images")
                    if (!outputDir.exists()) outputDir.mkdirs()
                    val fileName = "cinematic_${System.currentTimeMillis()}.jpg"
                    val outputFile = java.io.File(outputDir, fileName)
                    outputFile.writeBytes(bytes)

                    val finalPrompt = connection.getHeaderField("X-Final-Prompt")?.let { raw ->
                        try {
                            java.net.URLDecoder.decode(raw, "UTF-8")
                        } catch (e: Exception) {
                            Log.w(TAG, "Could not decode X-Final-Prompt: ${e.message}")
                            null
                        }
                    }
                    Result.success(WorkerImageResult(outputFile, finalPrompt))
                } else {
                    val errorStream = connection.errorStream
                    val errorText = errorStream?.bufferedReader()?.use { it.readText() } ?: "HTTP $responseCode"
                    val errorMsg = try {
                        org.json.JSONObject(errorText).optString("error", errorText)
                    } catch (e: Exception) { errorText }
                    Result.failure(Exception("$errorMsg (HTTP $responseCode)"))
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e(TAG, "Error calling Cloudflare Worker generate-image: ${e.message}", e)
                Result.failure(e)
            }
        }
    }
